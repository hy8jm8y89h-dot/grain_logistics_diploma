def generate_final_report(
    selected_region: str,
    selected_port: str,
    best_route,
    savings: dict,
    market_risk: dict,
    forecast_summary: dict,
    terminal_summary: dict,
    effective_rail_change: float,
    effective_auto_change: float,
    effective_river_change: float
) -> str:
    """
    Формирует итоговый текстовый отчет по результатам работы аналитической системы.
    """

    report = f"""
По результатам работы аналитической системы для направления «{selected_region} — {selected_port}» выполнено сравнение альтернативных схем доставки зерна.

Оптимальным вариантом перевозки определен маршрут «{best_route['route_type']}» со стоимостью {best_route['cost_rub_t']} руб./т. Экономия относительно наиболее дорогого варианта составляет {savings['max_saving']} руб./т, или {savings['max_saving_percent']}%.

С учетом заданного сценария изменение железнодорожного тарифа составляет {effective_rail_change}%, изменение автомобильного тарифа — {effective_auto_change}%, изменение речной составляющей — {effective_river_change}%. Это позволяет оценить устойчивость выбранного маршрута к изменению тарифной и рыночной конъюнктуры.

Интегральный индекс рыночного риска составляет {market_risk['risk_score']} из 100. Система классифицирует ситуацию как «{market_risk['status']}». Данный показатель учитывает валютный курс, мировую цену зерна, изменение стоимости топлива, загруженность морских портов и новостной риск.

По прогнозному модулю объем перевозок зерна речным транспортом к {forecast_summary['last_year']} году оценивается на уровне {forecast_summary['last_volume']} тыс. т. Рост относительно начального года составляет {forecast_summary['growth_percent']}%.

Модуль оценки терминальной инфраструктуры показывает, что суммарная пропускная способность выбранной сети терминалов составляет {terminal_summary['total_capacity']} тыс. т, плановый объем распределения — {terminal_summary['total_volume']} тыс. т, средняя загрузка терминалов — {terminal_summary['average_load']}%. Количество терминалов с перегрузкой составляет {terminal_summary['overloaded_count']}.

Таким образом, разработанная система позволяет выполнять комплексную оценку маршрута перевозки зерна с учетом стоимости доставки, изменения тарифов, внешних рыночных факторов, прогнозной динамики грузопотока и загрузки речной терминальной инфраструктуры.
"""

    return report.strip()